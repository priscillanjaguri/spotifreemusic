"""Playback sessions and listening events (the raw data behind all analytics)."""
import uuid
from datetime import date, datetime

from sqlalchemy import (
    BigInteger, Boolean, CheckConstraint, Date, DateTime, ForeignKey, Index, Integer, String, func,
)
from sqlalchemy.dialects.postgresql import UUID, ExcludeConstraint
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base
from app.models.catalog import Song


class PlaybackSession(Base):
    """One continuous stretch of the player being used (open app -> idle/close)."""

    __tablename__ = "playback_sessions"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), index=True
    )
    provider_id: Mapped[int | None] = mapped_column(ForeignKey("music_providers.id", ondelete="SET NULL"))
    started_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
    ended_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    # Optional id generated by the client player so retried requests are idempotent.
    client_session_id: Mapped[str | None] = mapped_column(String(64))

    events: Mapped[list["ListeningEvent"]] = relationship(back_populates="session")

    __table_args__ = (
        Index(
            "uq_playback_sessions_user_client",
            "user_id", "client_session_id",
            unique=True,
            postgresql_where="client_session_id IS NOT NULL",
        ),
    )


class ListeningEvent(Base):
    """One uninterrupted *segment* of listening to one song.

    Key decisions:
    * `listened_ms` is actual audible time. Paused time is excluded by the
      client/service before insertion, so it is never counted.
    * `started_at`/`ended_at` are the wall-clock span. A database EXCLUSION
      constraint forbids two events for the same user overlapping in time,
      which prevents double-counting (e.g. the same play reported twice, or
      two devices reporting at once).
    * `play_date` is the date in the user's timezone *at the time of listening*.
      Weekly/monthly reports group on it, so old reports never shift if the user
      later changes timezone.
    * `song_duration_ms` is a snapshot, so completion % stays valid even if
      catalogue metadata is corrected later.
    """

    __tablename__ = "listening_events"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    user_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"))
    # RESTRICT: catalogue songs with history are never hard-deleted.
    song_id: Mapped[int] = mapped_column(ForeignKey("songs.id", ondelete="RESTRICT"))
    session_id: Mapped[int | None] = mapped_column(ForeignKey("playback_sessions.id", ondelete="SET NULL"))
    started_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    ended_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    listened_ms: Mapped[int] = mapped_column(Integer)
    song_duration_ms: Mapped[int] = mapped_column(Integer)
    completed: Mapped[bool | None] = mapped_column(Boolean)  # NULL = provider can't tell us
    play_date: Mapped[date] = mapped_column(Date)

    song: Mapped[Song] = relationship()
    session: Mapped[PlaybackSession | None] = relationship(back_populates="events")

    __table_args__ = (
        CheckConstraint("listened_ms >= 0", name="listened_non_negative"),
        CheckConstraint("song_duration_ms > 0", name="duration_positive"),
        CheckConstraint("ended_at >= started_at", name="time_order"),
        # Audible time can't exceed the wall-clock span (+1s tolerance for clock jitter).
        CheckConstraint(
            "listened_ms <= EXTRACT(EPOCH FROM (ended_at - started_at)) * 1000 + 1000",
            name="listened_within_span",
        ),
        ExcludeConstraint(
            ("user_id", "="),
            (func.tstzrange(started_at, ended_at, "[)"), "&&"),
            using="gist",
            name="ex_listening_events_no_overlap",
        ),
        Index("ix_listening_events_user_started", "user_id", "started_at"),
        Index("ix_listening_events_user_play_date", "user_id", "play_date"),
        Index("ix_listening_events_song_id", "song_id"),
    )
